/** Small deterministic hash so stats and picks are stable per id. */
function hash(input: string): number {
  let value = 0;
  for (let i = 0; i < input.length; i += 1) {
    value = (value * 31 + input.charCodeAt(i)) >>> 0;
  }
  return value;
}

function deskFor(category: string): DeskPack {
  const key = categoryDeskMap[category];
  return deskPacks[key ?? "state"];
}

/** Builds the full reading body for any wire article. */
export function buildArticleBody(article: Article): ArticleBody {
  const desk = deskFor(article.category);
  const seed = hash(article.id);

  const sections: ArticleSection[] = desk.sections.map((section, index) => ({
    id: `section-${index + 1}`,
    heading: section.heading,
    paragraphs: section.paragraphs,
    points: section.points,
  }));

  const comments = Array.from({ length: 3 }, (_, index) => {
    const template = commentPool[(seed + index) % commentPool.length];
    return { id: `${article.id}-c${index}`, ...template };
  });

  return {
    intro: [
      `${article.headline} याबाबतची सर्व माहिती एकत्रित करून त्यामागील पार्श्वभूमी आणि पुढील परिणाम यांचा ठळक आढावा येथे मांडला आहे.`,
      ...desk.intro,
    ],
    keyPoints: desk.keyPoints,
    sections,
    tags: desk.tags,
    author: authors[seed % authors.length],
    published: article.meta.includes("·")
      ? `प्रकाशित: ${article.meta.split("·").pop()?.trim()}`
      : `प्रकाशित: ${article.meta}`,
    updated: seed % 2 === 0 ? "अद्ययावत: आज सकाळी १०:३०" : undefined,
    readTime: `${3 + (seed % 4)} मिनिटे वाचन`,
    stats: {
      likes: 120 + (seed % 480),
      dislikes: 4 + (seed % 26),
      comments: comments.length,
      shares: 30 + (seed % 220),
    },
    comments,
  };
}

